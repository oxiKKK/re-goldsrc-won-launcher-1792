#include <new>
#include <string.h>

#include "WriteBuffer.h"

///////////////////////////////////////////////////////////////////////////////
///////////////////////////////////////////////////////////////////////////////
WriteBuffer::WriteBuffer( const WriteBuffer &other )
{
	mCapacity = other.mCapacity;
	mSize = other.mSize;
	mBuffer = new unsigned char[mCapacity];
	memcpy( mBuffer, other.mBuffer, mSize );
}

///////////////////////////////////////////////////////////////////////////////
///////////////////////////////////////////////////////////////////////////////
WriteBuffer::WriteBuffer( int size )
{
	mBuffer = new unsigned char[size];
	mCapacity = size;
	mSize = 0;
}

///////////////////////////////////////////////////////////////////////////////
///////////////////////////////////////////////////////////////////////////////
WriteBuffer::~WriteBuffer()
{
	delete[] mBuffer;
}

///////////////////////////////////////////////////////////////////////////////
///////////////////////////////////////////////////////////////////////////////
WriteBuffer &WriteBuffer::operator=( const WriteBuffer &other )
{
	if ( this == &other )
		return *this;

	delete[] mBuffer;
	mCapacity = other.mCapacity;
	mSize = other.mSize;
	mBuffer = new unsigned char[mCapacity];
	memcpy( mBuffer, other.mBuffer, mSize );
	return *this;
}

///////////////////////////////////////////////////////////////////////////////
///////////////////////////////////////////////////////////////////////////////
void WriteBuffer::appendString( const std::string &value )
{
	unsigned short len;

	len = value.length();
	appendShort( len );
	append( value.c_str(), len );
}

///////////////////////////////////////////////////////////////////////////////
///////////////////////////////////////////////////////////////////////////////
void WriteBuffer::appendWString( const std::wstring &value )
{
	unsigned short len;

	len = value.length();
	appendShort( len );
	append( value.data(), 2 * len );
}

///////////////////////////////////////////////////////////////////////////////
///////////////////////////////////////////////////////////////////////////////
void WriteBuffer::rewind( void )
{
	mSize = 0;
}

///////////////////////////////////////////////////////////////////////////////
///////////////////////////////////////////////////////////////////////////////
void WriteBuffer::setShort( int offset, short value )
{
	setBuf( offset, &value, 2 );
}

///////////////////////////////////////////////////////////////////////////////
///////////////////////////////////////////////////////////////////////////////
int WriteBuffer::getSize( void ) const
{
	return mSize;
}

///////////////////////////////////////////////////////////////////////////////
///////////////////////////////////////////////////////////////////////////////
unsigned char *WriteBuffer::getBuffer( void ) const
{
	return mBuffer;
}

///////////////////////////////////////////////////////////////////////////////
///////////////////////////////////////////////////////////////////////////////
void WriteBuffer::setBuf( int offset, const void *data, unsigned int len )
{
	if ( offset + len > mCapacity )
		reallocAndCopy( 2 * (offset + len) );

	memcpy( mBuffer + offset, data, len );
}

///////////////////////////////////////////////////////////////////////////////
///////////////////////////////////////////////////////////////////////////////
void WriteBuffer::append( const void *data, unsigned int len )
{
	if ( mSize + len >= mCapacity )
		reallocAndCopy( 2 * (len + mCapacity) );

	memcpy( mBuffer + mSize, data, len );
	mSize += len;
}

///////////////////////////////////////////////////////////////////////////////
///////////////////////////////////////////////////////////////////////////////
void WriteBuffer::appendByte( unsigned char value )
{
	append( &value, 1 );
}

///////////////////////////////////////////////////////////////////////////////
///////////////////////////////////////////////////////////////////////////////
void WriteBuffer::appendShort( unsigned short value )
{
	append( &value, 2 );
}

///////////////////////////////////////////////////////////////////////////////
///////////////////////////////////////////////////////////////////////////////
void WriteBuffer::appendLong( unsigned int value )
{
	append( &value, 4 );
}

///////////////////////////////////////////////////////////////////////////////
///////////////////////////////////////////////////////////////////////////////
void WriteBuffer::setLong( int offset, unsigned int value )
{
	setBuf( offset, &value, 4 );
}

///////////////////////////////////////////////////////////////////////////////
///////////////////////////////////////////////////////////////////////////////
void WriteBuffer::reallocAndCopy( unsigned int size )
{
	unsigned char *newBuffer;

	newBuffer = new unsigned char[size];
	memcpy( newBuffer, mBuffer, mSize );
	delete[] mBuffer;
	mBuffer = newBuffer;
	mCapacity = size;
}
