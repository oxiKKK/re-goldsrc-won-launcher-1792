#include <string.h>
#include <wchar.h>

#include "ReadBuffer.h"

///////////////////////////////////////////////////////////////////////////////
///////////////////////////////////////////////////////////////////////////////
ReadBuffer::ReadBuffer( const char *data, int len )
{
	setBuffer( data, len );
}

///////////////////////////////////////////////////////////////////////////////
///////////////////////////////////////////////////////////////////////////////
ReadBuffer::ReadBuffer()
{
	mBuffer = 0;
	mReadPos = 0;
	mBufferSize = 0;
}

///////////////////////////////////////////////////////////////////////////////
///////////////////////////////////////////////////////////////////////////////
void ReadBuffer::setBuffer( const char *data, unsigned long len )
{
	mBuffer = (unsigned char *)data;
	mReadPos = 0;
	mBufferSize = len;
}

///////////////////////////////////////////////////////////////////////////////
///////////////////////////////////////////////////////////////////////////////
int ReadBuffer::readString( std::string *value )
{
	const unsigned char *stringData;
	unsigned long len;

	stringData = getTheRest( &len );
	if ( !value )
		return 0;

	value->assign( (const char *)stringData, len );
	return 1;
}

///////////////////////////////////////////////////////////////////////////////
///////////////////////////////////////////////////////////////////////////////
int ReadBuffer::readUByte( unsigned char *value )
{
	if ( mBufferSize == mReadPos )
		return 0;

	*value = mBuffer[mReadPos];
	++mReadPos;
	return 1;
}

///////////////////////////////////////////////////////////////////////////////
///////////////////////////////////////////////////////////////////////////////
int ReadBuffer::readByte( char *value )
{
	unsigned char byteValue;

	if ( !readUByte( &byteValue ) )
		return 0;

	*value = (char)byteValue;
	return 1;
}

///////////////////////////////////////////////////////////////////////////////
///////////////////////////////////////////////////////////////////////////////
int ReadBuffer::readUShort( unsigned short *value )
{
	if ( mBufferSize - mReadPos < 2 )
		return 0;

	*value = *(unsigned short *)( mBuffer + mReadPos );
	mReadPos += 2;
	return 1;
}

///////////////////////////////////////////////////////////////////////////////
///////////////////////////////////////////////////////////////////////////////
int ReadBuffer::readShort( short *value )
{
	unsigned short shortValue;

	if ( !readUShort( &shortValue ) )
		return 0;

	*value = (short)shortValue;
	return 1;
}

///////////////////////////////////////////////////////////////////////////////
///////////////////////////////////////////////////////////////////////////////
int ReadBuffer::readULong( unsigned long *value )
{
	if ( mBufferSize - mReadPos < 4 )
		return 0;

	*value = *(unsigned long *)( mBuffer + mReadPos );
	mReadPos += 4;
	return 1;
}

///////////////////////////////////////////////////////////////////////////////
// 0x45AC10 -- a u16 wchar count followed by that many UTF-16 code units.
///////////////////////////////////////////////////////////////////////////////
int ReadBuffer::readWString( wchar_t *value, int cchMax )
{
	unsigned short count;
	unsigned long needed;
	const wchar_t *src;
	int copy, i;

	if ( !readUShort( &count ) )
		return 0;

	needed = 2 * (unsigned long)count;
	if ( mBufferSize - mReadPos < needed )
		return 0;

	src = (const wchar_t *)( mBuffer + mReadPos );
	copy = count;
	if ( copy > cchMax - 1 )
		copy = cchMax - 1;
	for ( i = 0; i < copy; i++ )
		value[i] = src[i];
	value[copy] = 0;

	mReadPos += needed;
	return 1;
}

///////////////////////////////////////////////////////////////////////////////
///////////////////////////////////////////////////////////////////////////////
int ReadBuffer::readLong( long *value )
{
	unsigned long longValue;

	if ( !readULong( &longValue ) )
		return 0;

	*value = (long)longValue;
	return 1;
}

///////////////////////////////////////////////////////////////////////////////
///////////////////////////////////////////////////////////////////////////////
const unsigned char *ReadBuffer::getTheRest( unsigned long *len )
{
	const unsigned char *data;

	if ( len )
		*len = mBufferSize - mReadPos;

	data = mBuffer + mReadPos;
	mReadPos = mBufferSize;
	return data;
}

///////////////////////////////////////////////////////////////////////////////
///////////////////////////////////////////////////////////////////////////////
int ReadBuffer::skipBytes( unsigned long len )
{
	if ( mBufferSize - mReadPos < len )
		return 0;

	mReadPos += len;
	return 1;
}

///////////////////////////////////////////////////////////////////////////////
///////////////////////////////////////////////////////////////////////////////
unsigned char *ReadBuffer::getDataPtr( void )
{
	return mBuffer + mReadPos;
}

///////////////////////////////////////////////////////////////////////////////
///////////////////////////////////////////////////////////////////////////////
unsigned long ReadBuffer::getRemainingSize( void )
{
	return mBufferSize - mReadPos;
}
